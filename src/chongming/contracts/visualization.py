"""Visualization contracts for Godot UI: incremental algorithm outputs for modes 2-4.

These contracts define the data flow from edge/center algorithms to Godot for
visualization and scoring. All timestamps use experiment time (nanoseconds),
never wall clock or frame counters. IDs follow existing event/measurement/track
identity rules from model.py and fusion.py.

Data is transmitted incrementally after each scenario step or algorithm invocation.
Godot maintains bounded history buffers and prunes by experiment time, not arrival order.
"""

from __future__ import annotations

from dataclasses import dataclass

from chongming.contracts.model import (
    CalibrationUsage,
    EventId,
    FusionStatus,
    MeasurementId,
    Rotation3x3,
    SessionId,
    StationId,
    TrackId,
    TrackLifecycle,
    Vec3,
)


@dataclass(frozen=True, kw_only=True)
class AlgorithmOutputUpdate:
    """Incremental algorithm output for one scenario step.

    Transmitted after each scenario step (modes 2-4) or algorithm invocation.
    update_id is monotonic within one run; scenario_time_ns and step_no come
    from the experiment clock, never wall time. Godot detects changes by
    comparing update_id and only processes newer updates.

    station_states provides per-station pose and calibration visualization.
    """

    update_id: int
    scenario_time_ns: int
    step_no: int
    edge_events: tuple[EdgeStationEvent, ...] | None
    center_events: CenterFusionEvent | None
    station_states: tuple[StationVisualizationState, ...] | None


@dataclass(frozen=True, kw_only=True)
class EdgeStationEvent:
    """Edge algorithm output for one station in one scenario step.

    Contains all rays and diagnostics generated by this station's edge algorithm
    during the step. Empty rays with diagnostics represents a processed frame
    with no detections or a calibration/detection failure.
    """

    station_id: StationId
    station_session_id: SessionId
    rays: tuple[RayVisualization, ...]
    diagnostics: tuple[DiagnosticSummary, ...]


@dataclass(frozen=True, kw_only=True)
class RayVisualization:
    """Minimal ray data for 3D line rendering and cross-referencing.

    event_id enables cross-referencing with center measurements' supporting_ray_ids.
    capture_time_ns is the exposure midpoint from CaptureTime; calibration_usage
    determines rendering color (VALID/FROZEN/STALE). detection_score [0,1] can
    modulate line thickness or intensity. angular_std_rad, if present, renders as
    a translucent cone around direction_enu_unit.
    """

    event_id: EventId
    capture_time_ns: int
    origin_enu_m: Vec3
    direction_enu_unit: Vec3
    calibration_usage: CalibrationUsage
    detection_score: float
    angular_std_rad: float | None


@dataclass(frozen=True, kw_only=True)
class DiagnosticSummary:
    """Edge failure summary for one frame or calibration event.

    category is a short label (calibration_lost, detection_failed, occlusion, etc.);
    reason_codes provide structured detail matching DiagnosticEvent conventions.
    """

    capture_time_ns: int
    category: str
    reason_codes: tuple[str, ...]


@dataclass(frozen=True, kw_only=True)
class CenterFusionEvent:
    """Center algorithm output for one processing step or window seal.

    Contains measurements and track updates generated during this center processing
    cycle. Batch-level counts summarize intermediate pipeline stages for diagnostics.
    voxel_space provides sparse scored voxels for candidate visualization (optional).
    """

    measurements: tuple[MeasurementVisualization, ...]
    tracks: tuple[TrackVisualization, ...]
    window_count: int
    candidate_count: int
    association_count: int
    voxel_space: VoxelSpaceVisualization | None


@dataclass(frozen=True, kw_only=True)
class MeasurementVisualization:
    """Minimal measurement data for 3D point and ellipsoid rendering.

    position_enu_m and position_std_enu_m are None when status != LOCATED.
    position_std_enu_m is the square root of covariance diagonal; render as red
    circle with diameter equal to the major axis (largest std component).
    supporting_ray_ids cross-references EdgeStationEvent rays for highlighting
    in mode 4. minimum_intersection_angle_deg and geometry_condition are quality
    metrics for diagnostic overlays.
    """

    measurement_id: MeasurementId
    reference_time_ns: int
    status: FusionStatus
    position_enu_m: Vec3 | None
    position_std_enu_m: Vec3 | None
    supporting_ray_ids: tuple[EventId, ...]
    supporting_station_ids: tuple[StationId, ...]
    minimum_intersection_angle_deg: float | None
    geometry_condition: float | None


@dataclass(frozen=True, kw_only=True)
class TrackVisualization:
    """Track state with incremental position for trajectory rendering.

    Godot maintains a bounded history ring buffer (e.g., 100 positions per track);
    this contract sends only the current state plus the newest position increment.
    recent_position_enu_m and recent_time_ns provide the newest history point;
    Godot appends it to the local buffer and prunes old entries. position_std_enu_m
    and velocity_std_enu_mps are square roots of covariance diagonals.

    Trajectory line color is determined by lifecycle: tentative (light red),
    confirmed (deep red), coasting (orange), deleted (gray). The current position
    marker uses the same color scheme.
    """

    track_id: TrackId
    event_time_ns: int
    lifecycle: TrackLifecycle
    position_enu_m: Vec3 | None
    velocity_enu_mps: Vec3 | None
    position_std_enu_m: Vec3 | None
    velocity_std_enu_mps: Vec3 | None
    recent_position_enu_m: Vec3 | None
    recent_time_ns: int | None


@dataclass(frozen=True, kw_only=True)
class TruthComparisonSnapshot:
    """Per-step ground truth for evaluation and overlay rendering.

    Transmitted alongside AlgorithmOutputUpdate for modes 2-4. Godot uses this
    for truth bounding boxes, trajectory comparisons, and scoring. Never sent to
    online algorithms.
    """

    targets: tuple[TruthTargetState, ...]


@dataclass(frozen=True, kw_only=True)
class TruthTargetState:
    """Ground truth target state for one scenario step.

    target_id matches scenario truth IDs, not online track IDs. geometry_type
    is sphere/box/aircraft for rendering correct bounding volumes. Green circle
    at position with velocity arrow; station-to-target lines drawn only when
    in_field_of_view (green thin line). Circle radius matches bounding geometry.
    """

    target_id: str
    time_ns: int
    position_enu_m: Vec3
    velocity_enu_mps: Vec3
    geometry_type: str
    bounding_radius_m: float
    visibility_by_station: tuple[TargetStationVisibility, ...]


@dataclass(frozen=True, kw_only=True)
class VoxelSpaceVisualization:
    """Sparse voxel scores for candidate space visualization.

    Only non-zero scored voxels are transmitted to reduce data volume. The search
    box and voxel step define the grid; scored_voxels contain sparse (index, score)
    pairs. Godot omits scores 0 (not sent) and 1 (insufficient support) from rendering.
    Scores 2 through 15 map linearly to opacity 0.2 through 0.5, clamped at
    the display bounds. max_score records the snapshot maximum, not a color scale.
    Typical sparsity: 1-5% of total voxel space.
    """

    search_box_min_enu_m: Vec3
    search_box_max_enu_m: Vec3
    voxel_step_enu_m: Vec3
    scored_voxels: tuple[ScoredVoxel, ...]
    max_score: int


@dataclass(frozen=True, kw_only=True)
class TargetStationVisibility:
    """Target visibility from one station's main camera for truth visualization.

    Determines whether to draw station-to-target line: only drawn when in_field_of_view
    is true (green thin line). capture_eligible indicates unobstructed line of sight.
    """

    station_id: StationId
    in_field_of_view: bool
    capture_eligible: bool


@dataclass(frozen=True, kw_only=True)
class StationVisualizationState:
    """Per-station pose and calibration state for visualization.

    Provides configured, actual (truth), and calibrated orientations for displaying
    calibration drift. Orientation errors are computed as (actual - configured) and
    (calibrated - configured). Display units: arcmin or arcsec for small angles.
    All rotations are R_enu_from_main (ENU to camera right/down/forward).
    """

    station_id: StationId
    configured_orientation_enu_from_main: Rotation3x3
    actual_orientation_enu_from_main: Rotation3x3 | None
    calibrated_orientation_enu_from_main: Rotation3x3 | None
    calibration_usage: CalibrationUsage | None
    truth_orientation_error_rad: Vec3 | None
    calibration_orientation_error_rad: Vec3 | None


@dataclass(frozen=True, kw_only=True)
class ScoredVoxel:
    """Single non-zero scored voxel in the candidate search space.

    grid_index is the integer grid coordinate (i, j, k) within the voxel space.
    World position is computed as: min + grid_index * step. score is an integer
    from voxel search (not float); sparse transmission skips score=0 voxels.
    supporting_station_count is the number of independent stations contributing
    rays through this voxel (optional diagnostic).
    """

    grid_index: tuple[int, int, int]
    score: int
    supporting_station_count: int
